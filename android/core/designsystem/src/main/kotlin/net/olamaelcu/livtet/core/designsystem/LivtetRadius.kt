package net.olamaelcu.livtet.core.designsystem

import androidx.compose.ui.unit.dp

/**
 * Corner-radius tokens. Mirrors `radius.*` in `packages/livtet-design-tokens/tokens.json`.
 *
 * Use [LivtetRadius.l] for cards and large surfaces, [LivtetRadius.m] for buttons and chips, and
 * [LivtetRadius.s] for small inline elements (badges, list-item tiles).
 */
object LivtetRadius {
    val s = 4.dp
    val m = 8.dp
    val l = 16.dp
}
